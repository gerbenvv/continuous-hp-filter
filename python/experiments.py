"""Generates the data and numbers used by the manuscript.

Writes the data files `paper/data/*.dat` and the LaTeX macros `paper/data/numbers.tex`, and
numerically verifies the theoretical statements made in the paper. Needs SciPy for the exact
smoothing-spline reference (`make_smoothing_spline`) and Node.js for the JavaScript timings.
"""

import json
import logging
import subprocess
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np
from scipy.interpolate import make_smoothing_spline

import chp
from chp import CHPSmoother, hp_filter, select_lambda

LOGGER: logging.Logger = logging.getLogger(__name__)

# Directory of this script, and the directory the paper's data files are written to.
SCRIPT_PATH: Path = Path(__file__).resolve().parent
OUTPUT_PATH: Path = SCRIPT_PATH.parent / "paper" / "data"

# The JavaScript implementation, timed through Node.js.
JAVASCRIPT_FILE_PATH: Path = SCRIPT_PATH.parent / "javascript" / "chp.js"

# Problem sizes (observations and knots) for the timing experiment.
TIMING_SIZES: tuple[int, ...] = (1_000, 3_000, 10_000, 30_000, 100_000, 300_000, 1_000_000)

# Node.js script that times the JavaScript implementation; prints `[n, fit ms, band ms]` rows.
NODE_TIMING_SCRIPT: str = r"""
const CHP = require(process.argv[1]);
const random = CHP.seededRandom(1);
const output = [];

for (const n of JSON.parse(process.argv[2])) {
    const xs = new Float64Array(n);
    const ys = new Float64Array(n);

    for (let i = 0; i < n; ++i) {
        xs[i] = random();
        ys[i] = Math.sin(6 * xs[i]) + 0.1 * random();
    }

    let best = Infinity;
    let bestBand = Infinity;

    for (let repeat = 0; repeat < 3; ++repeat) {
        let start = process.hrtime.bigint();
        const smoother = new CHP.CHPSmoother(0.01, { m: n }).fit(xs, ys);
        best = Math.min(best, Number(process.hrtime.bigint() - start) / 1e6);

        start = process.hrtime.bigint();
        smoother.std(0.5);
        bestBand = Math.min(bestBand, Number(process.hrtime.bigint() - start) / 1e6);
    }

    output.push([n, best, bestBand]);
}

console.log(JSON.stringify(output));
"""


class NumberCollector:
    """Collects numbers for the paper and writes them as LaTeX macros."""

    def __init__(self):
        self.numbers: dict[str, str] = {}

    def add(self, key: str, value: Any, format_spec: str = "{:.3g}") -> None:
        """Adds a number; formats with an `e` in them are written as `m \\times 10^{e}`."""

        text = format_spec.format(value)

        if "e" in format_spec:
            mantissa, exponent = text.split("e")
            text = f"{mantissa}\\times 10^{{{int(exponent)}}}"

        self.numbers[key] = f"\\ensuremath{{{text}}}"

    def save(self, file_path: Path) -> None:
        """Writes the numbers as `\\num<Key>` macros."""

        with file_path.open("w") as file:
            file.write("% Generated by python/experiments.py -- do not edit.\n")

            for key, value in self.numbers.items():
                file.write(f"\\newcommand{{\\num{key[0].upper() + key[1:]}}}{{{value}}}\n")


def save_columns(name: str, columns: list[Any], header: str) -> None:
    """Saves columns of numbers as a whitespace-separated data file for pgfplots."""

    np.savetxt(OUTPUT_PATH / name, np.column_stack(columns), header=header, comments="", fmt="%.8g")


def get_truth(x: np.ndarray) -> np.ndarray:
    """Returns the smooth test function used in most experiments."""

    return np.sin(2 * np.pi * x) + 0.3 * np.cos(8 * np.pi * x) + 2 * x


def run_fit_experiment(numbers: NumberCollector, rng: np.random.Generator) -> None:
    """Fits irregular, weighted data with a gap and saves the fit, band and samples."""

    x = np.sort(rng.uniform(0, 1, 90))
    x = x[(x < 0.45) | (x > 0.62)]
    noise = np.where(x > 0.8, 0.35, 0.12)
    y = get_truth(x) + noise * rng.standard_normal(x.size)

    lam, _, _ = select_lambda(x, y, w=1 / noise**2)
    smoother = CHPSmoother(lam, bounds=(-0.05, 1.05)).fit(x, y, sigma=noise)

    grid = np.linspace(-0.05, 1.05, 600)
    samples = smoother.evaluate(smoother.sample(4, rng=11), grid)

    save_columns("fit_points.dat", [x, y, noise], "x y sigma")
    save_columns(
        "fit_curve.dat", [grid, smoother(grid), smoother.std(grid), get_truth(grid)], "x f sd truth"
    )
    save_columns("fit_samples.dat", [grid, *samples], "x s1 s2 s3 s4")

    coverage_grid = np.linspace(0, 1, 400)
    error = np.abs(smoother(coverage_grid) - get_truth(coverage_grid))
    covered = error < 1.96 * smoother.std(coverage_grid)

    numbers.add("fitLambda", lam)
    numbers.add("fitKnots", smoother.m_, "{:d}")
    numbers.add("fitEdf", smoother.edf)
    numbers.add("fitN", x.size, "{:d}")
    numbers.add("fitCoverage", 100 * np.mean(covered), "{:.0f}")


def run_exactness_experiment(numbers: NumberCollector, rng: np.random.Generator) -> None:
    """Compares with the exact smoothing spline, on the knots and off the knots."""

    # Data on the knots: the result must equal the exact smoothing spline.
    x = np.linspace(0, 1, 101)
    y = get_truth(x) + 0.1 * rng.standard_normal(x.size)
    fine = np.linspace(0, 1, 5001)
    exact_errors = []

    for m in (101, 201, 401):
        smoother = CHPSmoother(0.05, m=m).fit(x, y)
        exact = make_smoothing_spline(x, y, w=np.full(x.size, 1 / x.size), lam=smoother.alpha_)
        exact_errors.append(np.max(np.abs(smoother(fine) - exact(fine))))

    numbers.add("exactError", max(exact_errors), "{:.1e}")

    # Irregular data: the result converges to the exact smoothing spline as the grid is refined.
    x = np.sort(rng.uniform(0, 1, 200))
    y = get_truth(x) + 0.1 * rng.standard_normal(x.size)
    fine = np.linspace(x.min(), x.max(), 20001)
    convergence = {}

    for bandwidth in (0.01, 0.03, 0.1):
        exact = None
        rows = []

        for ratio in (0.25, 0.5, 1, 2, 4, 8, 16, 32):
            m = int(np.ceil((x.max() - x.min()) * ratio / bandwidth)) + 1
            smoother = CHPSmoother(bandwidth, m=m, normalization="data").fit(x, y)

            if exact is None:
                weights = np.full(x.size, 1 / x.size)
                exact = make_smoothing_spline(x, y, w=weights, lam=smoother.alpha_)

            error = np.max(np.abs(smoother(fine) - exact(fine))) / np.ptp(exact(fine))
            rows.append((bandwidth / smoother.dt_, error))

        convergence[bandwidth] = np.array(rows)
        save_columns(
            f"convergence_{bandwidth:g}.dat",
            [convergence[bandwidth][:, 0], convergence[bandwidth][:, 1]],
            "ratio error",
        )

    # Empirical order from the finest steps of the middle bandwidth.
    rows = convergence[0.03]
    slope = np.polyfit(np.log(rows[-4:, 0]), np.log(rows[-4:, 1]), 1)[0]

    numbers.add("convergenceOrder", -slope, "{:.1f}")
    numbers.add("convergenceAtEight", rows[rows[:, 0] >= 7.5][0, 1], "{:.1e}")

    # Scale invariance on the same irregular data.
    reference = CHPSmoother(0.05, m=200).fit(x, y)
    worst = 0.0

    for scale in (1e-6, 1e-3, 60.0, 86400.0, 1e6):
        scaled = CHPSmoother(0.05 * scale, m=200).fit(x * scale, y)
        worst = max(worst, np.max(np.abs(scaled.knots[1] - reference.knots[1])))

    numbers.add("scaleError", worst, "{:.1e}")


def run_kernel_experiment(numbers: NumberCollector) -> None:
    """Compares the impulse response for dense uniform data with Silverman's kernel."""

    num_points = 4001
    bandwidth = 0.05
    x = np.linspace(-1, 1, num_points)
    impulse = np.zeros(num_points)
    impulse[num_points // 2] = 1.0

    smoother = CHPSmoother(bandwidth, m=num_points, normalization=2.0).fit(x, impulse)

    u = np.linspace(-6 * bandwidth, 6 * bandwidth, 601)
    kernel = smoother(u) / (x[1] - x[0])

    def get_silverman_kernel(v: Any) -> Any:
        scaled = np.abs(v) / (np.sqrt(2) * bandwidth)

        return 1 / (2 * bandwidth) * np.exp(-scaled) * np.sin(scaled + np.pi / 4)

    silverman = get_silverman_kernel(u)
    save_columns(
        "kernel.dat", [u / bandwidth, kernel * bandwidth, silverman * bandwidth], "u ours silverman"
    )

    numbers.add(
        "kernelError", np.max(np.abs(kernel - silverman)) / get_silverman_kernel(0.0), "{:.1e}"
    )


def run_hp_experiment(numbers: NumberCollector) -> None:
    """Checks the Ravn-Uhlig rule on one signal sampled monthly, quarterly and annually."""

    years = 60.0

    # Trend plus a 30-year and a 6-year cycle; noise-free so differences are purely due to the
    # filter.
    t_month = np.arange(0, years, 1 / 12)
    y_month = 0.03 * t_month + 0.4 * np.sin(2 * np.pi * t_month / 30)
    y_month += 0.1 * np.sin(2 * np.pi * t_month / 6)

    t_quarter, y_quarter = t_month[::3], y_month[::3]
    t_year, y_year = t_month[::12], y_month[::12]

    hp_quarter = hp_filter(y_quarter, 1600.0)
    hp_month_fourth = hp_filter(y_month, 1600.0 * 3**4)
    hp_year_fourth = hp_filter(y_year, 1600.0 / 4**4)
    hp_month_square = hp_filter(y_month, 1600.0 * 3**2)
    hp_year_square = hp_filter(y_year, 1600.0 / 4**2)

    bandwidth = chp.lambda_from_hp(1600.0, 0.25)

    numbers.add("equivalentBandwidth", bandwidth, "{:.2f}")
    numbers.add("cutoffYears", 2 * np.pi * bandwidth, "{:.1f}")

    # Compare at common annual dates, 5 years away from the ends.
    common = t_year[(t_year >= 5) & (t_year <= years - 5)]

    def get_difference(t: np.ndarray, values: np.ndarray, reference: np.ndarray) -> float:
        return np.max(np.abs(np.interp(common, t, values) - reference))

    reference = np.interp(common, t_quarter, hp_quarter)

    numbers.add("ruFourMonth", get_difference(t_month, hp_month_fourth, reference), "{:.1e}")
    numbers.add("ruFourYear", get_difference(t_year, hp_year_fourth, reference), "{:.1e}")
    numbers.add("ruTwoMonth", get_difference(t_month, hp_month_square, reference), "{:.1e}")
    numbers.add("ruTwoYear", get_difference(t_year, hp_year_square, reference), "{:.1e}")

    samplings = dict(
        month=(t_month, y_month), quarter=(t_quarter, y_quarter), year=(t_year, y_year)
    )
    smoothers = {
        label: CHPSmoother(
            bandwidth, dt=1 / 48, bounds=(0, t_month[-1]), normalization=t_month[-1]
        ).fit(t, values)
        for label, (t, values) in samplings.items()
    }

    quarter = smoothers["quarter"](common)

    numbers.add("ourMonth", np.max(np.abs(smoothers["month"](common) - quarter)), "{:.1e}")
    numbers.add("ourYear", np.max(np.abs(smoothers["year"](common) - quarter)), "{:.1e}")
    numbers.add("ourVsHp", np.max(np.abs(quarter - reference)), "{:.1e}")
    numbers.add("signalRange", np.ptp(y_month), "{:.2f}")

    save_columns(
        "ru_quarter.dat",
        [t_quarter, y_quarter, hp_quarter, smoothers["quarter"](t_quarter)],
        "t y hp ours",
    )
    save_columns(
        "ru_year.dat",
        [t_year, y_year, hp_year_fourth, hp_year_square, smoothers["year"](t_year)],
        "t y hp4 hp2 ours",
    )
    save_columns(
        "ru_month.dat",
        [t_month, hp_month_fourth, hp_month_square, smoothers["month"](t_month)],
        "t hp4 hp2 ours",
    )


def get_iwp_covariance(s: float, t: float) -> np.ndarray:
    """Returns the covariance of `(X(s), X'(s))` and `(X(t), X'(t))`.

    Here `X` is the integral of a unit Brownian motion with `X(0) = X'(0) = 0`.
    """

    low, high = min(s, t), max(s, t)

    value_value = low * low * (3 * high - low) / 6
    value_slope = (s * s / 2) if s <= t else (t * s - t * t / 2)  # Cov(X(s), X'(t)).
    slope_value = (t * t / 2) if t <= s else (s * t - s * s / 2)  # Cov(X'(s), X(t)).
    slope_slope = low

    return np.array([[value_value, value_slope], [slope_value, slope_slope]])


def run_bayesian_experiment(numbers: NumberCollector) -> None:
    """Checks the integrated-Wiener-process marginal, the bridge variance and band coverage."""

    # The joint density of `(f(t_j), f'(t_j))` under the integrated Wiener process (unit
    # diffusion) follows `x_{j+1} = F x_j + e_j` with `e_j ~ N(0, Q)`. Its exponent equals the
    # Hermite curvature energy.
    delta = 0.37
    transition = np.array([[1, delta], [0, 1]])
    noise_covariance = np.array([[delta**3 / 3, delta**2 / 2], [delta**2 / 2, delta]])

    difference = np.hstack([-transition, np.eye(2)])
    iwp = difference.T @ np.linalg.inv(noise_covariance) @ difference

    # With `p = delta f'`, the Hermite parameters are `(h, p) = scale (f, f')`.
    scale = np.diag([1, delta, 1, delta])
    hermite = scale @ (chp.ELEMENT_STIFFNESS / delta**3) @ scale

    numbers.add("iwpError", np.max(np.abs(iwp - hermite)) / np.max(np.abs(hermite)), "{:.1e}")

    # The bridge variance inside a knot interval, given values and slopes at both ends.
    t0, t1 = 1.0, 1.0 + delta
    ends = np.block([[get_iwp_covariance(a, b) for b in (t0, t1)] for a in (t0, t1)])
    ratios = []

    for fraction in np.linspace(0.05, 0.95, 19):
        s = t0 + fraction * delta
        cross = np.hstack([get_iwp_covariance(s, t0)[0], get_iwp_covariance(s, t1)[0]])
        variance = get_iwp_covariance(s, s)[0, 0] - cross @ np.linalg.solve(ends, cross)
        predicted = (fraction * delta) ** 3 * ((1 - fraction) * delta) ** 3 / (3 * delta**3)
        ratios.append(variance / predicted)

    numbers.add("bridgeError", np.max(np.abs(np.array(ratios) - 1)), "{:.1e}")

    # Frequentist coverage of the 95% band (known noise), averaged over the function.
    rng = np.random.default_rng(21)
    probe = np.linspace(0.02, 0.98, 97)
    hits = []

    for _ in range(100):
        x = np.sort(rng.uniform(0, 1, 150))
        y = get_truth(x) + 0.2 * rng.standard_normal(x.size)

        lam, _, _ = select_lambda(x, y, lams=np.logspace(-2.5, -0.5, 9))
        smoother = CHPSmoother(lam, normalization="data").fit(x, y, sigma=0.2)

        hits.append(np.abs(smoother(probe) - get_truth(probe)) < 1.96 * smoother.std(probe))

    numbers.add("coverage", 100 * np.mean(hits), "{:.1f}")


def run_gcv_experiment(numbers: NumberCollector, rng: np.random.Generator) -> None:
    """Saves the GCV curve and effective degrees of freedom as a function of the bandwidth."""

    x = np.sort(rng.uniform(0, 1, 150))
    y = get_truth(x) + 0.15 * rng.standard_normal(x.size)

    best, lams, scores = select_lambda(x, y, lams=np.logspace(-3, 0, 40))
    edfs = [CHPSmoother(lam).fit(x, y).edf for lam in lams]

    save_columns("gcv.dat", [lams, scores, edfs], "lam gcv edf")
    numbers.add("gcvBest", best, "{:.3f}")


def measure_time(function: Callable[[], Any]) -> tuple[Any, float]:
    """Returns the result of `function` and its run time in milliseconds."""

    start = time.perf_counter()
    result = function()

    return result, (time.perf_counter() - start) * 1e3


def run_timing_experiment(numbers: NumberCollector, rng: np.random.Generator) -> None:
    """Times the Python (LAPACK through SciPy) and JavaScript (Node.js) implementations."""

    timing = []

    for n in TIMING_SIZES:
        x = rng.uniform(0, 1, n)
        y = get_truth(x) + 0.1 * rng.standard_normal(n)

        smoother, fit_time = measure_time(lambda: CHPSmoother(0.01, m=n).fit(x, y))

        # The pure-Python selected inverse is skipped for the largest size.
        band_time = np.nan
        if n <= 300_000:
            _, band_time = measure_time(lambda: smoother.covariance_band)

        timing.append((n, fit_time, band_time))

    completed = subprocess.run(
        ["node", "-e", NODE_TIMING_SCRIPT, str(JAVASCRIPT_FILE_PATH), json.dumps(TIMING_SIZES)],
        capture_output=True,
        text=True,
        check=True,
    )

    timing = np.array(timing)
    javascript = np.array(json.loads(completed.stdout))

    save_columns(
        "timing.dat",
        [timing[:, 0], timing[:, 1], timing[:, 2], javascript[:, 1], javascript[:, 2]],
        "n py pyband js jsband",
    )

    numbers.add("jsMillion", javascript[-1, 1], "{:.0f}")
    numbers.add("pyMillion", timing[-1, 1], "{:.0f}")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    OUTPUT_PATH.mkdir(parents=True, exist_ok=True)

    numbers = NumberCollector()

    # One generator is shared, in this order, so that the results are reproducible.
    rng = np.random.default_rng(3)

    run_fit_experiment(numbers, rng)
    run_exactness_experiment(numbers, rng)
    run_kernel_experiment(numbers)
    run_hp_experiment(numbers)
    run_bayesian_experiment(numbers)
    run_gcv_experiment(numbers, rng)
    run_timing_experiment(numbers, rng)

    numbers.save(OUTPUT_PATH / "numbers.tex")

    for key, value in numbers.numbers.items():
        LOGGER.info("%-22s %s", key, value)


if __name__ == "__main__":
    main()
